"""Regenerates outputs/samples/: five sample questions with their drafts, the appended doc entries and the email drafts.
Run: python make_samples.py   (writes only inside outputs/samples/; the PAN used for the redaction sample is a dummy built at run time)"""
import os
import shutil
from pathlib import Path

ROOT = Path(__file__).parent
S = ROOT / "outputs" / "samples"
if S.exists():
    shutil.rmtree(S)
(S / "written").mkdir(parents=True)
(S / "logs").mkdir()
os.environ["DESK_OUT"] = str(S / "written")
os.environ["DESK_LOGS"] = str(S / "logs")

from service import Service  # noqa: E402

PAN = "ABCDE" + "1234F"
svc = Service()
svc.seed()
run = svc.run_weekly()
doc, email = run["action_ids"]
svc.decide_action(doc, True)          # approval 1: doc entry (also registers the canonical explainer)
svc.decide_action(email, True)        # approval 2: email draft, separate click

QS = [("Fee question, answered from the approved canonical explainer", "Why was brokerage deducted again when I sold my shares?"),
      ("Scheme fact from the Milestone 1 corpus", "What is the exit load of HDFC Small Cap Fund?"),
      ("Question the corpus cannot answer", "Do HDFC funds invest in cryptocurrency?"),
      ("Advice request (refused)", "Should I redeem my HDFC Small Cap Fund units?"),
      ("Message containing a PAN (redacted before storage)", f"My PAN is {PAN}. Why is a DP charge applied when I sell?")]
out = ["# Sample outputs\n", f"Generated by `make_samples.py` from the shipped queue and the {run['window']} review window.\n",
       "## Five sample questions and their drafts\n"]
first = None
for i, (kind, q) in enumerate(QS, 1):
    tid = svc.submit_question(q)
    first = first or tid
    t, m = svc.desk.tickets[tid], svc.meta[tid]
    f = t["outputs"]["facts"]
    out += [f"### {i}. {kind}\n", f"**Question as stored (redacted):** {t['message']}\n",
            f"- Detected intent: {svc.intent_of(t)}", f"- Facts: {f['status']}" + (f" -> {f['citation_url']}" if f['status'] == 'covered' else f" (searched: {'; '.join(f['searched'][-3:])})"),
            f"- Reviewer: {'passed' if t['review']['passed'] else 'FLAGGED'}", "",
            "**Reply draft**\n", "> " + t["draft"]["reply"]["full_text"].replace("\n", "\n> "), "",
            f"**Routing note:** {t['draft']['routing']['note']}\n"]
svc.decide_ticket(first, True)
w = S / "written"
out += ["## Weekly pulse run\n", f"```\n{run['pulse']}\n```\n", "## Appended doc entry (after approving the weekly doc action)\n",
        "```markdown\n" + (w / "weekly_log.md").read_text(encoding="utf-8") + "```\n",
        "## Weekly email draft (after approving the weekly email action; never sent)\n",
        "```text\n" + (w / "weekly_pulse_draft.txt").read_text(encoding="utf-8") + "\n```\n",
        "## Support record appended after approving question 1\n", "```markdown\n" + (w / "support_log.md").read_text(encoding="utf-8") + "```\n",
        "## Reply email draft for question 1 (never sent)\n", "```text\n" + (w / "support_reply_draft.txt").read_text(encoding="utf-8") + "\n```\n"]
(S / "sample_outputs.md").write_text("\n".join(out), encoding="utf-8")
print("wrote", S / "sample_outputs.md")
